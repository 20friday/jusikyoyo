const HOLIDAYS = new Set([
  // 2026 공휴일 및 장운영 특이일
  '2026-01-01', // 신정
  '2026-01-28', // 설날 연휴
  '2026-01-29', // 설날
  '2026-01-30', // 설날 다음날
  '2026-03-01', // 삼일절
  '2026-05-05', // 어린이날
  '2026-05-15', // 부처님오신날
  '2026-05-26', // 대체공휴일
  '2026-06-06', // 현충일
  '2026-08-15', // 광복절
  '2026-09-24', // 추석 연휴
  '2026-09-25', // 추석
  '2026-09-26', // 추석 다음날
  '2026-10-03', // 개천절
  '2026-10-09', // 한글날
  '2026-12-25', // 크리스마스
  '2026-12-31', // 연말폐장일
]);

export function isKoreanMarketHoliday(dateStr: string): boolean {
  const d = new Date(dateStr + 'T00:00:00');
  const day = d.getDay();
  if (day === 0 || day === 6) return true; // 토·일
  return HOLIDAYS.has(dateStr);
}
